func getTypeString(expr ast.Expr) string {
	switch t := expr.(type) {
	case *ast.Ident:
		return t.Name
	case *ast.StarExpr:
		baseType := getTypeString(t.X)
		if baseType == "File" {
			return "*os.File"
		}
		return "*" + baseType
	default:
		return "nil"
	}
}

// Формирует строковое представление вложенной структуры
func getStructTypeString(structType *ast.StructType) string {
	fields := []string{}
	for _, field := range structType.Fields.List {
		if field.Names != nil {
			for _, name := range field.Names {
				fields = append(fields, name.Name)
			}
		}
	}
	return fmt.Sprintf("struct{%s}", strings.Join(fields, " "))
}
